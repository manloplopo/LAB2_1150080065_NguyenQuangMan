    private void btn_encryptActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_encryptActionPerformed
       String plaintext = txt_plaintext.getText();
if (plaintext.isEmpty()) {
JOptionPane.showMessageDialog(this, "Hãy nhập Plaintext trước khi mã hóa.");
return;
}
try {
String ciphertext = RC4Cipher.encrypt(plaintext, txt_key.getText());
txt_ciphertext.setText(ciphertext);
lbl_status.setText("<html>Đã mã hóa RC4. " + HistoryDao.tryInsert("RC4", "ENCRYPT", null,
plaintext.length(), ciphertext.length()) + "</html>");
} catch (IllegalArgumentException ex) {JOptionPane.showMessageDialog(this, ex.getMessage(),"Dữ liệu không hợp lệ", JOptionPane.ERROR_MESSAGE);
} catch (Exception ex) {JOptionPane.showMessageDialog(this, "Mã hóa thất bại:\n" + ex.getMessage(),"Lỗi", JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_btn_encryptActionPerformed

    private void btn_decryptActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_decryptActionPerformed
        String ciphertext = txt_ciphertext.getText();
if (ciphertext.isEmpty()) {
JOptionPane.showMessageDialog(this, "Hãy nhập Ciphertext trước khi giải mã.");
return;
}
try {
String plaintext = RC4Cipher.decrypt(ciphertext, txt_key.getText());
txt_plaintext.setText(plaintext);
lbl_status.setText("<html>Đã giải mã RC4. " + HistoryDao.tryInsert("RC4", "DECRYPT", null,
ciphertext.length(), plaintext.length()) + "</html>");
} catch (IllegalArgumentException ex) {
JOptionPane.showMessageDialog(this, ex.getMessage(),
"Dữ liệu không hợp lệ", JOptionPane.ERROR_MESSAGE);
} catch (Exception ex) {JOptionPane.showMessageDialog(this, "Giải mã thất bại: sai Key hoặc bản mã bị sửa.\n" +ex.getMessage(),"Lỗi", JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_btn_decryptActionPerformed

    private void btn_saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_saveActionPerformed
      String path = FileTextIO.saveText(this, txt_ciphertext, "rc4_ciphertext.txt");
if (path != null) {
lbl_status.setText("Đã lưu tệp: " + path);
}
    }//GEN-LAST:event_btn_saveActionPerformed

    private void btn_openActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_openActionPerformed
        String path = FileTextIO.openText(this, txt_ciphertext);
if (path != null) {
lbl_status.setText("Đã mở tệp: " + path);
}
    }//GEN-LAST:event_btn_openActionPerformed

